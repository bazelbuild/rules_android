# Integration test verifying that singlejar can ingest META-INF/desugar_deps
# metadata generated by Desugar.

set -euo pipefail

readonly DESUGAR="$1"; shift
readonly SINGLEJAR="$1"; shift
readonly BOOTCLASSPATH="$1"; shift
readonly BASIC_JAR="$1"; shift
readonly INTERFACES_JAR="$1"; shift
readonly CLASSES_JAR="$1"; shift
readonly JUST_K_JAR="$1"; shift
readonly MISSING_INTERFACE_JAR="$1"; shift
readonly UNZIP="$1"; shift
readonly FORMAT="$1"; shift

readonly basic_desugared="${TEST_TMPDIR}/basic_desugared.jar"
readonly interfaces_desugared="${TEST_TMPDIR}/interfaces_desugared.jar"
readonly classes_desugared="${TEST_TMPDIR}/classes_desugared.jar"
readonly just_k_desugared="${TEST_TMPDIR}/just_k_desugared.jar"
readonly missing_interface_desugared="${TEST_TMPDIR}/missing_interface_desugared.jar"

# 1. Generate desugared jars with META-INF/desugar_deps using Desugar.
"$DESUGAR" \
  --bootclasspath_entry "$BOOTCLASSPATH" \
  --emit_dependency_metadata_as_needed \
  --desugar_deps_format "$FORMAT" \
  -i "$BASIC_JAR" -o "$basic_desugared" \
  -i "$INTERFACES_JAR" -o "$interfaces_desugared" \
  -i "$JUST_K_JAR" -o "$just_k_desugared" \
  -i "$MISSING_INTERFACE_JAR" -o "$missing_interface_desugared"

"$DESUGAR" \
  --bootclasspath_entry "$BOOTCLASSPATH" \
  --classpath_entry "$INTERFACES_JAR" \
  --emit_dependency_metadata_as_needed \
  --desugar_deps_format "$FORMAT" \
  -i "$CLASSES_JAR" -o "$classes_desugared"

for jar in \
  "$basic_desugared" \
  "$interfaces_desugared" \
  "$classes_desugared" \
  "$just_k_desugared" \
  "$missing_interface_desugared"; do
  "$UNZIP" -l "$jar" META-INF/desugar_deps >/dev/null
done

if [[ "$FORMAT" == "json" ]]; then
  # TODO(b/576977305): Enable once the singlejar change is submitted.
  echo "PASS"
  exit 0
fi

# 2. Verify singlejar succeeds on a self-contained desugared jar and strips
# META-INF/desugar_deps from the output jar.
readonly basic_out="${TEST_TMPDIR}/basic_out.jar"
"$SINGLEJAR" \
  --check_desugar_deps \
  --output "$basic_out" \
  --sources "$basic_desugared"
if "$UNZIP" -l "$basic_out" META-INF/desugar_deps >/dev/null 2>&1; then
  echo "Expected singlejar to strip META-INF/desugar_deps from output jar" >&2
  exit 1
fi

# 3. Verify singlejar succeeds when combining separately desugared classes and
# interfaces jars (satisfying assume_present companion class dependencies).
readonly combined_out="${TEST_TMPDIR}/combined_out.jar"
"$SINGLEJAR" \
  --check_desugar_deps \
  --output "$combined_out" \
  --sources "$classes_desugared" "$interfaces_desugared"

# 4. Verify singlejar succeeds when a missing interface is not present with
# default methods in the combined sources.
readonly missing_interface_alone_out="${TEST_TMPDIR}/missing_interface_alone_out.jar"
"$SINGLEJAR" \
  --check_desugar_deps \
  --output "$missing_interface_alone_out" \
  --sources "$missing_interface_desugared"

# 5. Verify singlejar fails when a companion class required by assume_present is
# missing from the combined sources.
readonly missing_companion_out="${TEST_TMPDIR}/missing_companion_out.jar"
readonly missing_companion_err="${TEST_TMPDIR}/missing_companion.err"
if "$SINGLEJAR" \
  --check_desugar_deps \
  --output "$missing_companion_out" \
  --sources "$classes_desugared" 2>"$missing_companion_err"; then
  echo "Expected singlejar to fail when companion classes are missing" >&2
  exit 1
fi
grep -q "referenced by .* but not found" "$missing_companion_err"

# 6. Verify singlejar fails when an interface recorded in missing_interface is
# defined with default methods (interface_with_companion) in another source jar.
readonly missing_interface_violation_out="${TEST_TMPDIR}/missing_interface_violation_out.jar"
readonly missing_interface_err="${TEST_TMPDIR}/missing_interface.err"
if "$SINGLEJAR" \
  --check_desugar_deps \
  --output "$missing_interface_violation_out" \
  --sources "$missing_interface_desugared" "$just_k_desugared" 2>"$missing_interface_err"; then
  echo "Expected singlejar to fail when an interface with default methods was missing from the desugar classpath" >&2
  exit 1
fi
grep -q "needed on the classpath for desugaring" "$missing_interface_err"

echo "PASS"
